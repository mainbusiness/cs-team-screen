# (עיר, שורה 1) → חייב להגיע לרשימת הבדיקה של ארז (ניחוש פאזי שנראה בטוח). נמדד 2026-10-10 בסט האמת.
REVIEW = [
    ('חריש', 'שוהם 22'),                                   # → "חורפיש" 2515500
    ('Rishon Lezion (rishon LeẔiyyon)', 'Nehemia 132'),   # → "רשפון" 4691500
    ('נתניה', 'Ground Floor'),                             # → רחוב "גרנדוס"
]
NO_REVIEW = [('תל מונד', 'הכלנית 16'), ('Carmiel', 'הדקל 33')]

def main():
    fails = []
    for c, t, st, n in PARSE:
        got = z.parse_street(t, c)
        if got != (st, n): fails.append(f'פירוק "{t}": {got} ≠ {(st, n)}')
    for c, a1, a2, exp, src in ZIPS:
        r = z.resolve(c, a1, a2)
        if r['zip'] != exp: fails.append(f'מיקוד {c} | {a1} | {a2}: {r["zip"]} [{r["level"]}] ≠ {exp} ({src})')
    for c, a1, a2, zc, act, must in BAD:
        o = {'city': c, 'address1': a1, 'address2': a2, 'zip': zc, 'country': 'IL'}
        if z.classify(o) != 'BAD_ADDRESS':
            fails.append(f'כתובת {c} | {a1} | {a2}: לא סווגה כלא תקינה ({z.classify(o)})'); continue
        f = z.fix_bad(o)
        if f['action'] != act or (must and must not in (f['address'] or '')):
            fails.append(f'כתובת {c} | {a1} | {a2}: {f["action"]} "{f["address"]}" ≠ {act} "{must}"')
    for c, a1 in REVIEW:
        z.FUZZY.clear(); r = z.resolve(c, a1, '')
        if not z.needs_review({'city': c}, r): fails.append(f'בדיקה {c} | {a1}: {r["zip"]} [{r["level"]}] יצא לספקית בלי סימון')
    for c, a1 in NO_REVIEW:
        z.FUZZY.clear(); r = z.resolve(c, a1, '')
        w = z.needs_review({'city': c}, r)
        if w: fails.append(f'בדיקה {c} | {a1}: סומן בלי סיבה ({w})')
    z.save_cache(force=True)
    total = len(PARSE) + len(ZIPS) + len(BAD) + len(REVIEW) + len(NO_REVIEW)
    print(f'selftest: {total - len(fails)}/{total} עברו')
    for f in fails: print('  ❌', f)
    sys.exit(1 if fails else 0)


if __name__ == '__main__':
    main()
